import frappe
from frappe import _
from frappe.model.document import Document
from frappe.utils import flt, getdate

from srv_erp.production.service import lock_assignment, positive_qty, require_planner, submitted_qty
from srv_erp.production.setup import validate_supervisor


class SRVProductionAssignment(Document):
	def _save(self, *args, **kwargs):
		if not self.is_new():
			lock_assignment(self.name)
		return super()._save(*args, **kwargs)

	def validate(self):
		if self.is_new():
			if not self.flags.from_production_schedule:
				frappe.throw(_("Assignments must be generated by submitting a production schedule."))
			self.status = "Planned"
			self.completed_qty = 0
			self.remaining_qty = self.target_qty
			return
		require_planner(self.company)
		previous, docstatus = lock_assignment(self.name)
		if docstatus != 1:
			frappe.throw(_("The production schedule is not active."))
		for key in (
			"schedule",
			"schedule_item",
			"responsibility",
			"work_area",
			"occurrence_key",
			"company",
			"template",
			"item_code",
			"uom",
		):
			if self.get(key) != previous.get(key):
				frappe.throw(_("The source and item of a generated assignment cannot be changed."))
		validate_supervisor(self.supervisor)
		self.target_qty = positive_qty(self.target_qty)
		completed = submitted_qty(self.name)
		if self.target_qty < completed:
			frappe.throw(_("Target quantity cannot be less than submitted production."))
		changed = (
			getdate(self.planned_date) != getdate(previous.planned_date)
			or self.supervisor != previous.supervisor
			or self.target_qty != previous.target_qty
		)
		if changed and (not self.change_reason or self.change_reason == previous.change_reason):
			frappe.throw(_("Enter a new change reason to reschedule, reassign or change the target."))
		self.completed_qty = completed
		self.remaining_qty = flt(self.target_qty - completed, 6)
		self.percent_completed = flt(100 * completed / self.target_qty, 2)
		self.status = (
			"Completed" if completed >= self.target_qty else "In Progress" if completed else "Planned"
		)

	def on_update(self):
		if not self.flags.from_production_schedule:
			from srv_erp.production.service import refresh_schedule_progress

			refresh_schedule_progress(self.schedule)

	def on_trash(self):
		frappe.throw(_("Generated assignments must be retained for audit history."))
